import { BuildingStyle, CityProfile, DistrictDef, defaultProfile } from "../config/city";
import { createSeededRandom, SeededRandom } from "./random";
import { riverBand } from "./landscape";
import { generateRoads, RoadSegment } from "./roads";

export interface BuildingRecord {
  x: number;
  z: number;
  height: number;
  footprint: [number, number];
  type: BuildingStyle;
  /** District name, or "Outskirts" when outside every district region */
  district: string;
}

/** Reserved, building-free plot for a landmark, addressable by profile name */
export interface LandmarkPlot {
  name: string;
  x: number;
  z: number;
}

export interface GeneratedCity {
  buildings: BuildingRecord[];
  landmarkPlots: LandmarkPlot[];
}

/** Grid spacing between building plots, world units */
export const PLOT_SPACING = 12;
/** Style used for plots outside every district (city-generation spec: fallback) */
export const DEFAULT_DISTRICT_STYLE: BuildingStyle = "lowrise";
/** Buildings are kept this far (world units) from every landmark plot */
export const LANDMARK_CLEARANCE = 10;

/** Invalid generation params fall back to defaults per field, never crash */
function sanitizeGeneration(g: CityProfile["generation"]): CityProfile["generation"] {
  const def = defaultProfile.generation;
  const extent = Number.isFinite(g.extent) && g.extent > 0 ? g.extent : def.extent;
  const density = Number.isFinite(g.density) && g.density >= 0 && g.density <= 1 ? g.density : def.density;
  const hr = g.heightRange;
  const heightRange =
    Array.isArray(hr) && hr.length === 2 && Number.isFinite(hr[0]) && Number.isFinite(hr[1]) && hr[0] < hr[1]
      ? hr
      : def.heightRange;
  return { extent, density, heightRange };
}

/** One plot per landmark: district center, nudged to stay ≥ PLOT_SPACING apart */
function placeLandmarks(profile: CityProfile): LandmarkPlot[] {
  const plots: LandmarkPlot[] = [];
  for (const l of profile.landmarks) {
    const d = profile.districts.find((x) => x.name === l.district);
    let x = d?.center[0] ?? 0;
    const z = d?.center[1] ?? 0;
    while (plots.some((p) => Math.hypot(p.x - x, p.z - z) < PLOT_SPACING)) {
      x += PLOT_SPACING;
    }
    plots.push({ name: l.name, x, z });
  }
  return plots;
}

function districtAt(districts: DistrictDef[], x: number, z: number): DistrictDef | undefined {
  for (const d of districts) {
    if (Math.hypot(x - d.center[0], z - d.center[1]) <= d.radius) return d;
  }
  return undefined;
}

function footprintFor(style: BuildingStyle, rng: SeededRandom): [number, number] {
  const variant = rng.next() < 0.5;
  switch (style) {
    case "highrise": return variant ? [8, 8] : [10, 6];
    case "midrise": return variant ? [8, 8] : [6, 10];
    case "lowrise": return variant ? [7, 7] : [9, 5];
    case "campus": return variant ? [12, 8] : [8, 12];
    case "park": return [0, 0];
  }
}

/** True when a building's footprint rect touches any road corridor rect */
function onRoad(x: number, z: number, fp: [number, number], roads: RoadSegment[]): boolean {
  const hx = fp[0] / 2;
  const hz = fp[1] / 2;
  for (const r of roads) {
    const hw = r.width / 2;
    const x0 = Math.min(r.from[0], r.to[0]);
    const x1 = Math.max(r.from[0], r.to[0]);
    const z0 = Math.min(r.from[1], r.to[1]);
    const z1 = Math.max(r.from[1], r.to[1]);
    const hit =
      r.from[1] === r.to[1] // horizontal corridor: z band across its x span
        ? x0 < x + hx && x - hx < x1 && r.from[1] - hw < z + hz && z - hz < r.from[1] + hw
        : r.from[0] - hw < x + hx && x - hx < r.from[0] + hw && z0 < z + hz && z - hz < z1;
    if (hit) return true;
  }
  return false;
}

/**
 * Pure, deterministic city generator. Same profile seed ⇒ identical layout.
 * Buildings are kept clear of the road corridors generated by generateRoads.
 */
export function generateCity(profile: CityProfile): GeneratedCity {
  const rng = createSeededRandom(profile.seed);
  const { extent, density, heightRange } = sanitizeGeneration(profile.generation);
  const landmarkPlots = placeLandmarks(profile);
  // The district containing the city center (origin) is the shaped core
  const coreName = districtAt(profile.districts, 0, 0)?.name;
  const band = profile.water?.enabled ? riverBand(profile) : undefined;
  const roads = generateRoads(profile);
  const cols = Math.floor(extent / PLOT_SPACING);
  const buildings: BuildingRecord[] = [];

  for (let gz = -cols; gz <= cols; gz++) {
    for (let gx = -cols; gx <= cols; gx++) {
      const x = gx * PLOT_SPACING;
      const z = gz * PLOT_SPACING;
      if (landmarkPlots.some((p) => Math.hypot(x - p.x, z - p.z) < LANDMARK_CLEARANCE)) continue;
      // plots whose footprint would reach the river are left empty
      if (band && z + PLOT_SPACING / 2 > band.z0 && z - PLOT_SPACING / 2 < band.z1) continue;
      const district = districtAt(profile.districts, x, z);
      if (district?.style === "park") continue;

      const style = district?.style ?? DEFAULT_DISTRICT_STYLE;
      const footprint = footprintFor(style, rng);
      // plots a road corridor would occupy are left empty
      if (onRoad(x, z, footprint, roads)) continue;

      const isCore = coreName !== undefined && district?.name === coreName;
      const baseDensity = district ? district.density * density : density * 0.5;
      const plotDensity = isCore ? Math.min(1, baseDensity + 0.1) : baseDensity;
      if (rng.next() > plotDensity) continue;

      const range = district?.heightRange ?? heightRange;
      // Core heights bias toward the top of the range so the core reads tallest
      const t = isCore ? 0.4 + 0.6 * rng.next() : rng.next();
      const height = range[0] + t * (range[1] - range[0]);

      buildings.push({
        x,
        z,
        height,
        footprint,
        type: style,
        district: district?.name ?? "Outskirts",
      });
    }
  }

  return { buildings, landmarkPlots };
}
